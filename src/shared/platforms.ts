export const PLATFORM_LABELS = {
  pending: "等待检查",
  checking: "正在检查",
  reachable: "入口可连接",
  auth_required: "入口要求登录",
  restricted: "访问受限",
  busy: "平台响应异常",
  network_error: "网络连接失败",
  check_failed: "检测未完成",
  cancelled: "已停止检查",
} as const;

export function platformHelpText(scan: PlatformScan, result: PlatformResult) {
  const platform = AI_PLATFORMS.find((p) => p.id === result.platformId)!;
  return [
    `AI 工具网络检查：${platform.name}`,
    `入口：${platform.url}`,
    `检查时间：${result.checkedAt ? new Date(result.checkedAt).toISOString() : "尚未完成"}`,
    `结果：${PLATFORM_LABELS[result.status]}`,
    `说明：${result.summary}`,
    `网络路径：${result.route}`,
    ...(result.paths || []).map((p) => `路径结果：${p.label} · ${p.status === "accessible" ? `收到 HTTP ${p.httpStatus}，网络可达` : p.status === "restricted" ? `收到 HTTP ${p.httpStatus}，平台拒绝访问` : p.status === "network_reachable" ? "TLS 安全连接已建立，但没有 HTTP 响应" : p.status === "unreachable" ? `连接失败${p.code ? ` (${p.code})` : ""}` : "未执行"}`),
    `建议：${result.suggestion}`,
    `HTTP（系统入口）：${result.httpStatus ?? "无响应记录"}`,
    ...result.evidence.map(
      (e) =>
        `${e.source === "Chromium · system network" ? "系统网络" : e.route === "direct" ? "补充直连" : "补充代理"} · ${e.stage}: ${e.status}${e.code ? ` (${e.code})` : ""}${e.httpStatus ? ` HTTP ${e.httpStatus}` : ""}`,
    ),
    "范围：仅检查平台公开入口；未验证账号、聊天生成、文件上传或客户端实际请求。",
    scan.detectionError
      ? "应用识别不可用。"
      : "应用识别仅通过运行进程名称匹配。",
  ].join("\n");
}
